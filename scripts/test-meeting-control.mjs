import { chromium, expect } from '@playwright/test';
import { mkdtemp, mkdir, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { basename, dirname, join, resolve } from 'node:path';

const root = resolve(tmpdir());
const work = await mkdtemp(join(root, 'meetkeep-control-'));
const profile = join(work, 'profile');
await mkdir(join(profile, 'Default'), { recursive: true });
await mkdir(join(work, 'downloads'));
await writeFile(join(profile, 'Default', 'Preferences'), JSON.stringify({ download: { default_directory: join(work, 'downloads'), prompt_for_download: false } }));
const extension = resolve('dist');
const title = 'Meet - Full-page recording test';
const html = `<!doctype html><html><head><title>${title}</title><style>
body{margin:0;background:#22334e;font:16px system-ui;color:white}main{display:grid;place-items:center;width:75vw;height:calc(100vh - 56px);font-size:34px}aside{position:fixed;right:0;top:0;width:25vw;height:calc(100vh - 56px);box-sizing:border-box;padding:25px;background:rgb(34,197,94);color:#12352b}footer{position:fixed;bottom:0;left:0;right:0;height:56px;background:rgb(245,158,11);color:#402e16;display:flex;gap:25px;justify-content:center;align-items:center}button{font:14px system-ui;padding:9px 16px;border:0;border-radius:18px;cursor:pointer}#clock{font-size:15px;color:#abc}
</style></head><body><main><div>Meeting content<div id="clock"></div><button id="join">Join meeting</button></div></main><aside><h3>Meeting chat</h3><p>Full-page capture includes this chat panel.</p></aside><footer><span>Captions and meeting controls</span><button id="leave" aria-label="Leave call" hidden>Leave</button></footer><script>
setInterval(()=>document.querySelector('#clock').textContent=new Date().toLocaleTimeString(),500);
document.querySelector('#join').onclick=async()=>{const audio=new AudioContext();await audio.resume();const tone=audio.createOscillator();const gain=audio.createGain();gain.gain.value=.01;tone.connect(gain).connect(audio.destination);tone.start();document.querySelector('#join').hidden=true;document.querySelector('#leave').hidden=false};
document.querySelector('#leave').onclick=()=>document.querySelector('#leave').remove();
</script></body></html>`;
let context;
try {
  console.log('Launching real tab-capture test; picker auto-selection is confined to this isolated test browser.');
  context = await chromium.launchPersistentContext(profile, { channel: 'chromium', headless: true, acceptDownloads: true, downloadsPath: join(work, 'downloads'), viewport: { width: 1280, height: 800 }, args: [`--disable-extensions-except=${extension}`, `--load-extension=${extension}`, `--auto-select-tab-capture-source-by-title=${title}`] });
  const worker = context.serviceWorkers()[0] ?? await context.waitForEvent('serviceworker');
  const id = new URL(worker.url()).hostname;
  const library = await context.newPage();
  await library.goto(`chrome-extension://${id}/library.html`);
  await expect(library.getByRole('heading', { name: 'Your meetings, kept.' })).toBeVisible();
  const state = () => library.evaluate(async () => (await chrome.runtime.sendMessage({ type: 'OVERVIEW' })).data.session);
  const records = () => library.evaluate(() => new Promise((resolve, reject) => { const request=indexedDB.open('meetkeep'); request.onerror=()=>reject(request.error); request.onsuccess=()=>{const db=request.result;const query=db.transaction('recordings','readonly').objectStore('recordings').getAll();query.onsuccess=()=>{resolve(query.result.sort((a,b)=>b.startedAt-a.startedAt));db.close()};query.onerror=()=>reject(query.error)}; }));
  const meeting = await context.newPage();
  meeting.on('pageerror', error => console.log('Meeting error:', error.message));
  await meeting.route('https://meet.google.com/**', route => route.fulfill({ contentType: 'text/html', body: html }));
  await meeting.goto('https://meet.google.com/meet/abc-defg-hij');
  const popup = await context.newPage();
  await popup.goto(`chrome-extension://${id}/popup.html`);
  await meeting.bringToFront();
  await expect(popup.getByRole('button', { name: 'Start recording', exact: true })).toBeEnabled();
  const detected = await library.evaluate(async () => (await chrome.runtime.sendMessage({ type: 'OVERVIEW' })).data.tab);
  expect(detected?.url).toBe('https://meet.google.com/meet/abc-defg-hij');
  await popup.close();
  await meeting.bringToFront();
  await meeting.getByRole('button', { name: 'Join meeting' }).click();
  const start = meeting.getByRole('button', { name: 'Start recording this meeting' });
  await expect(start).toBeEnabled();
  await expect(start).toHaveText('');
  await expect(start).toHaveAttribute('aria-pressed', 'false');
  await expect.poll(() => meeting.evaluate(() => document.querySelector('#join').hidden)).toBe(true);
  expect((await state()).phase).toBe('idle');
  expect(await records()).toHaveLength(0);
  const box = await start.boundingBox();
  expect(box.x).toBe(8);
  expect(box.width).toBe(28);
  expect(box.height).toBe(28);
  expect(800 - box.y - box.height).toBe(8);
  await meeting.screenshot({ path: 'artifacts/meeting-not-recording.png' });
  await start.click();
  await expect.poll(async () => (await state()).phase, { timeout: 20_000 }).toBe('recording');
  const stop = meeting.getByRole('button', { name: 'Stop and save recording' });
  await expect(stop).toHaveText('');
  await expect(stop).toHaveAttribute('aria-pressed', 'true');
  await expect(stop).toHaveClass('recording');
  // Meet can move between URL aliases without changing the meeting itself.
  await meeting.evaluate(() => history.pushState(null, '', '/abc-defg-hij'));
  await expect.poll(async () => (await records())[0]?.size ?? 0, { timeout: 15_000 }).toBeGreaterThan(0);
  expect((await state()).phase).toBe('recording');
  await meeting.screenshot({ path: 'artifacts/meeting-recording.png' });
  console.log('The icon-only bottom-left button started full-tab recording and changed its status.');
  expect((await records())[0].source).toBe('tab');
  expect((await records())[0].title).toMatch(/^\d{4}-\d{2}-\d{2} \d{2}:\d{2} — Meet - Full-page recording test$/);
  expect((await library.evaluate(() => chrome.runtime.sendMessage({ type: 'PAUSE' }))).ok).toBe(true);
  const resume = meeting.getByRole('button', { name: 'Resume recording' });
  await expect(resume).toHaveClass('paused');
  await resume.click();
  await expect(stop).toHaveClass('recording');
  await stop.click();
  await expect.poll(async () => (await state()).phase, { timeout: 15_000 }).toBe('idle');
  await expect(start).toHaveText('');
  await expect(start).toHaveAttribute('aria-pressed', 'false');
  expect((await records())[0].status).toBe('saved');
  expect((await records())[0].webmIndexed).toBe(1);
  await expect.poll(() => worker.evaluate(async () => (await chrome.downloads.search({})).filter(item=>item.state==='complete').length), { timeout: 15_000 }).toBe(1);
  const pixels = await library.evaluate(async () => {
    const db = await new Promise((resolve, reject) => { const request = indexedDB.open('meetkeep'); request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error); });
    const chunks = await new Promise((resolve, reject) => { const request = db.transaction('chunks', 'readonly').objectStore('chunks').getAll(); request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error); });
    db.close();
    const blob = new Blob(chunks.sort((a,b)=>a.index-b.index).map(chunk=>chunk.data), {type:'video/webm'});
    const url = URL.createObjectURL(blob);
    const video = document.createElement('video'); video.muted=true; video.src=url;
    await new Promise((resolve,reject)=>{video.onloadeddata=resolve;video.onerror=()=>reject(new Error('Saved video did not decode.'))});
    const duration = video.duration;
    const seekableEnd = video.seekable.length ? video.seekable.end(0) : 0;
    const beforePlayback = video.paused;
    await new Promise((resolve,reject)=>{video.onseeked=resolve;video.onerror=()=>reject(new Error('Saved video did not seek.'));video.currentTime=duration*.6});
    const jumpedTo = video.currentTime;
    await video.play();
    await new Promise(resolve => setTimeout(resolve, 750));
    const canvas = document.createElement('canvas');canvas.width=video.videoWidth;canvas.height=video.videoHeight;
    const draw=canvas.getContext('2d');draw.drawImage(video,0,0);
    const pixel=(x,y)=>[...draw.getImageData(Math.floor(x*canvas.width),Math.floor(y*canvas.height),1,1).data].slice(0,3);
    const result={chat:pixel(.9,.5),controls:pixel(.5,.98),width:canvas.width,height:canvas.height,duration,seekableEnd,beforePlayback,jumpedTo,png:canvas.toDataURL('image/png')};
    video.pause();video.src='';URL.revokeObjectURL(url);return result;
  });
  await writeFile('artifacts/recorded-meeting-frame.png', Buffer.from(pixels.png.split(',')[1], 'base64'));
  console.log('Decoded tab pixels:', {chat:pixels.chat,controls:pixels.controls,width:pixels.width,height:pixels.height});
  expect(pixels.chat[1]).toBeGreaterThan(150); expect(pixels.chat[0]).toBeLessThan(100);
  expect(pixels.controls[0]).toBeGreaterThan(180); expect(pixels.controls[2]).toBeLessThan(100);
  expect(Number.isFinite(pixels.duration)).toBe(true);
  expect(pixels.duration).toBeGreaterThan(0);
  expect(pixels.seekableEnd).toBeCloseTo(pixels.duration, 1);
  expect(pixels.beforePlayback).toBe(true);
  expect(pixels.jumpedTo).toBeCloseTo(pixels.duration*.6, 1);
  console.log('Saved video decoded with the chat panel and meeting controls visible; download completed.');
  // Starting a second recording must still require an explicit click.
  expect(await records()).toHaveLength(1);
  await start.click();
  await expect.poll(async () => (await state()).phase, { timeout: 20_000 }).toBe('recording');
  await expect.poll(async () => (await records()).filter(record=>record.size>0).length, {timeout:15_000}).toBe(2);
  await meeting.close();
  await expect.poll(async () => (await state()).phase, {timeout:15_000}).toBe('idle');
  expect((await records()).some(record=>record.status==='interrupted' && record.size>0)).toBe(true);
  console.log('PASS: manual start, compact bottom-left indicator, full-tab pixels, pause/resume, stop/save, downloads, names, and tab-close recovery.');
} finally {
  await context?.close();
  if (dirname(resolve(work)) !== root || !basename(work).startsWith('meetkeep-control-')) throw new Error('Unexpected temporary path.');
  await rm(work, { recursive: true, force: true });
}
